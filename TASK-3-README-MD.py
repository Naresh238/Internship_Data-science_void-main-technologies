print("3. Boxplots help identify the spread and possible outliers.")
print("4. Correlation shows the relationship between different subject scores.")
print("5. Covariance shows how two variables change together.")
print("6. Bivariate analysis compares two variables.")
print("7. Multivariate analysis compares multiple subject scores.")
print("8. Hypothesis testing checks whether test preparation has a significant effect on math scores.")
